/**
 * 简 → 繁转换 —— **拒绝猜测的那一种**。
 *
 * ## 为什么原来的文档说「不做简转繁」，而这里做了
 *
 * 原话是：「不做『简转繁』自动降级 —— 本领域的高频字恰好落在一简对多繁的歧义区：
 * 余气→餘氣（非余氣）、历法→曆法（非歷法）、后天→後天（非后天）。
 * 机械转换会在术语上出错，而术语出错的报告比没有报告更糟。」
 *
 * 那句话反对的是**静默猜测**，不是转换本身。本模块的做法是：
 *
 * ```
 * 一简对多繁的字 → 必须逐字写明本领域取哪一个，并写明为什么；
 *                   写不出单一读法的（发、系、复），取值为 null，
 *                   此时若无词条覆盖，toHant **抛错**，不猜。
 * 一对一的字     → 单字表。歧义字进单字表即测试失败。
 * 简繁同形的字   → 逐字核过，列在 IDENTICAL 里。
 * ```
 *
 * 三个桶必须**覆盖输出里的每一个汉字**。出现第四类（未分类的新字）时
 * `hant.spec.ts` 报错并指名道姓 —— 忘记归类不会静默通过。
 *
 * ## 实测底数
 *
 * 三张盘的完整报告（含 §6.5）共 97 万字、808 个去重汉字，
 * 其中一简对多繁者 52 个，一对一者 247 个，同形者 509 个。
 * 歧义字只占 6%，且绝大多数在本领域内只有一个读法 —— 这正是本方案可行的原因。
 *
 * ## 匹配顺序
 *
 * ```
 * 1. EXACT   整串相等才用。给单独出现的表格单元用 —— 「发」独立成格时是肾之华（髮）
 * 2. TERMS   最长优先的词条。词条永远压过单字
 * 3. CHARS   一对一单字
 * 4. 歧义字   有 pick 用 pick；pick 为 null 且无词条覆盖 → 抛错
 * ```
 */

