export class UncoveredAmbiguityError extends Error {
  constructor(readonly chars: readonly string[], readonly text: string) {
    super(
      `简转繁遇到无法定夺的字：${chars.join("、")}\n`
      + `  原文：${text.slice(0, 80)}\n`
      + "  这些字一简对多繁，且本领域内无单一读法。请在 hant.ts 的 TERMS 里加词条，"
      + "或在 AMBIGUOUS 里写明取哪一个及其理由。**不要让它猜。**",
    );
    this.name = "UncoveredAmbiguityError";
  }
}

/**
 * 词条表**加上它自己的像** —— 这一步保证 `toHant` 幂等。
 *
 * 没有它会在生产里抛错，不是只在测试里：`renderMarkdown` 对整篇再转一遍，
 * 而篇中的叙述已经是繁体了。「系统」转成「系統」之后，`统` 已是繁体，
 * 「系统」这条词条不再命中，`系` 于是落单 —— 而 `系` 的 pick 是 null，
 * 于是抛「无法定夺」。把 `系統 → 系統` 一并登记，第二遍便原样吃掉。
 */
const TERMS_ALL: Record<string, string> = { ...TERMS };
for (const v of Object.values(TERMS)) if (!(v in TERMS_ALL)) TERMS_ALL[v] = v;
const EXACT_ALL: Record<string, string> = { ...EXACT };
for (const v of Object.values(EXACT)) if (!(v in EXACT_ALL)) EXACT_ALL[v] = v;

const MAX_TERM = Math.max(...Object.keys(TERMS_ALL).map((k) => k.length));
const IDENT = new Set([...IDENTICAL]);

/**
 * 转为繁体。遇到无法定夺的字**抛错**，不猜。
 *
 * ⚠️ 只用于引擎产出的文本。用户自填的标注不经此处 ——
 * 那是用户自己的字，代为改写不是本分。
 */
export function toHant(s: string): string {
  const out: string[] = [];
  const uncovered = new Set<string>();
  const exact = EXACT_ALL[s];
  if (exact !== undefined) return exact;

  let i = 0;
  while (i < s.length) {
    let hit = false;
    for (let n = Math.min(MAX_TERM, s.length - i); n >= 2; n--) {
      const t = TERMS_ALL[s.slice(i, i + n)];
      if (t !== undefined) { out.push(t); i += n; hit = true; break; }
    }
    if (hit) continue;

    const ch = s[i]!;
    const one = CHARS[ch];
    if (one !== undefined) { out.push(one); i++; continue; }
    const amb = AMBIGUOUS[ch];
    if (amb !== undefined) {
      if (amb.pick === null) uncovered.add(ch);
      out.push(amb.pick ?? ch);
      i++;
      continue;
    }
    out.push(ch);
    i++;
  }
  if (uncovered.size > 0) throw new UncoveredAmbiguityError([...uncovered], s);
  return out.join("");
}

/**
 * 文本里未被三个桶覆盖的汉字 —— 供完整性测试。
 *
 * 空集意味着「每个字都被明确归过类」，而不是「转换看起来没出错」。
 */
export function unclassifiedOf(s: string): string[] {
  const out = new Set<string>();
  for (const ch of s) {
    if (!/\p{Script=Han}/u.test(ch)) continue;
    if (ch in CHARS || ch in AMBIGUOUS || IDENT.has(ch)) continue;
    out.add(ch);
  }
  return [...out].sort();
}

/** 单字表的键 —— 这些字若出现在繁体输出里，说明有一处漏转。 */
export const SIMPLIFIED_ONLY: readonly string[] = Object.freeze(Object.keys(CHARS));

/**
 * 转换之后**合法**的汉字集：同形字，加上各表输出侧出现过的字。
 *
 * 它比「不是简体字」严格得多 —— 后者查不出漏归类的字（一个没归类的简体字
 * 既不在单字表的键里、也就不会被 `SIMPLIFIED_ONLY` 逮到，这是个循环）。
 * 用输出侧的白名单则没有这个循环：凡不在其中的，要么该归类，要么该加词条。
 */
const HANT_OUTPUT: ReadonlySet<string> = new Set([
  ...IDENTICAL,
  ...Object.values(CHARS),
  ...Object.values(TERMS).flatMap((v) => [...v]),
  ...Object.values(EXACT).flatMap((v) => [...v]),
  ...Object.values(AMBIGUOUS).flatMap((a) => (a.pick === null ? [] : [...a.pick])),
]);

/**
 * 已转换的文本里仍不合法的汉字 —— 说明有字漏了归类，那处转换是静默失败的。
 *
 * 用途：守卫的繁体规则由简体机械派生，漏归类的字会原样留在简体，
 * 于是那条繁体规则永远匹配不上繁体正文 —— 一个不报错的洞。实测漏过一个「险」。
 */
export function unconvertedOf(s: string): string[] {
  const out = new Set<string>();
  for (const ch of s) {
    if (!/\p{Script=Han}/u.test(ch)) continue;
    if (HANT_OUTPUT.has(ch)) continue;
    out.add(ch);
  }
  return [...out].sort();
}
